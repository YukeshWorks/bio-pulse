/**
 * Generates DEMONSTRATION DATA for local development (`npm run demo:generate`).
 *
 * The data is produced by running the real pipeline against synthetic API responses, then
 * post-processed so it can never be mistaken for real research:
 *   - dataset: "demo" (the production validator refuses to deploy it),
 *   - every title is prefixed with "[DEMO]",
 *   - every link points to example.org, never to a real article,
 *   - identifiers use the reserved test DOI prefix 10.5555 / fictional numbers.
 * Output: fixtures/demo/ (served only by the Vite dev server in demo mode, never built into dist/).
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { DailyDatasetSchema, type DailyDataset } from '../shared/schema';
import { createMemoryLogger } from '../pipeline/lib/log';
import { runPipeline } from '../pipeline/pipeline';
import { BIORXIV_JSON, happyRoutes, json, mockFetch, PUBMED_ARTICLES, pubmedEfetchXml, TEST_ENV, testConfig, testHttp, text } from '../tests/helpers';

const OUT = path.resolve('fixtures/demo');

const EXTRA_PUBMED = [
  ['99000011', 'Engineered mesenchymal stem cell organoids accelerate cartilage regeneration in a rat defect model', 'We engineered organoids from induced pluripotent stem cells. The regenerated tissue improved compared with untreated controls. Results are limited to a rodent model.'],
  ['99000012', 'A wearable aptamer biosensor for continuous cortisol monitoring in sweat', 'Here we describe an electrochemical aptamer biosensor integrated in a wearable patch. The sensor outperformed a commercial immunoassay in a pilot study of 12 volunteers.'],
  ['99000013', 'Precision fermentation of milk proteins using an engineered Pichia strain', 'We developed a Pichia pastoris strain for precision fermentation of beta-lactoglobulin. Titers improved threefold over previous strains. Further scale-up studies are needed.'],
  ['99000014', 'Microbial consortia degrade polyethylene terephthalate under ambient conditions', 'We identified a bacterial consortium capable of PET biodegradation. Degradation was preliminary and measured over 30 days in vitro.'],
  ['99000015', 'Deep learning prediction of antibody developability from sequence', 'We present a deep learning model that predicts monoclonal antibody aggregation from sequence. The model improved accuracy compared with existing tools.'],
  ['99000016', 'Drought tolerant wheat generated by multiplex genome editing', 'We generated drought tolerant wheat using multiplex CRISPR genome editing. Field validation remains to be performed.'],
  ['99000017', 'Continuous perfusion bioreactor process for monoclonal antibody manufacturing', 'We report a continuous perfusion bioprocess using CHO cells. Productivity improved compared with fed-batch culture.'],
  ['99000018', 'Lipid nanoparticle formulation improves mRNA delivery to lung epithelium', 'We designed a lipid nanoparticle library for pulmonary delivery. However, toxicity in larger animals remains unknown.'],
  ['99000019', 'Bioactive compounds from a marine sponge-associated microalga inhibit biofilm formation', 'We identified marine microalgae metabolites with antibiofilm activity. Findings are limited to in vitro assays.'],
].map(([pmid, title, abstract]) => ({ pmid, title, abstract, doi: `10.5555/demo.${pmid}` }));

const EXTRA_BIORXIV = [
  ['10.5555/demo.rxiv.10', 'De novo designed protein binders neutralise a model toxin', 'bioengineering', 'We designed de novo protein binders with directed evolution refinement. This is the first design approach of its kind for this toxin.'],
  ['10.5555/demo.rxiv.11', 'Single-cell multi-omics atlas of engineered T cells during expansion', 'bioinformatics', 'We present a single-cell RNA sequencing atlas of CAR-T cells. Further validation is required.'],
].map(([doi, title, category, abstract]) => ({ doi, title, authors: 'Garcia, M.; Ito, H.', author_corresponding_institution: 'Demo Institute', date: '', version: '1', type: 'new results', category, abstract, published: 'NA', server: 'biorxiv' }));

function demoRoutes(date: string, slice: [number, number]) {
  const all = [...PUBMED_ARTICLES, ...EXTRA_PUBMED].slice(...slice);
  const rxiv = { ...BIORXIV_JSON, collection: [...BIORXIV_JSON.collection, ...EXTRA_BIORXIV].map((c) => ({ ...c, date })) };
  return happyRoutes({
    pubmed: (u) =>
      u.includes('esearch')
        ? json({ esearchresult: { idlist: all.map((a) => a.pmid) } })
        : text(pubmedEfetchXml(all.map((a) => ({ ...a, year: date.slice(0, 4), month: date.slice(5, 7), day: date.slice(8, 10) })))),
    biorxiv: () => json(rxiv),
  });
}

function toDemo(d: DailyDataset): DailyDataset {
  const fake = (id: string) => `https://example.org/biopulse-demo/${id}`;
  return {
    ...d,
    dataset: 'demo',
    notice: 'DEMONSTRATION DATA — fictional records generated from synthetic test fixtures for development. This is not real or current research.',
    briefing: d.briefing.sentence
      ? { ...d.briefing, note: 'DEMO: generated from fictional demonstration records.' }
      : d.briefing,
    records: d.records.map((r) => ({
      ...r,
      title: r.title.startsWith('[DEMO]') ? r.title : `[DEMO] ${r.title}`,
      url: fake(r.id),
      alsoIndexedIn: r.alsoIndexedIn.map((a) => ({ ...a, url: fake(`${r.id}-${a.id}`) })),
      organization: r.organization,
    })),
  };
}

async function main() {
  await fs.rm(OUT, { recursive: true, force: true });
  const work = path.join(OUT, '.work');
  const days: [string, [number, number]][] = [
    ['2026-11-16', [3, 7]],
    ['2026-11-17', [7, 10]],
    ['2026-11-18', [0, 12]],
  ];
  for (const [date, slice] of days) {
    await runPipeline({
      // Demo days intentionally overlap; disable "already published" suppression so each day is populated.
      config: testConfig(work, { seenWindowDays: 0 }),
      http: testHttp(mockFetch(demoRoutes(date, slice))),
      log: createMemoryLogger(),
      env: TEST_ENV,
      now: new Date(`${date}T01:30:00Z`),
    });
  }
  // Convert every generated file to demo form.
  await fs.mkdir(path.join(OUT, 'archive'), { recursive: true });
  for (const f of await fs.readdir(path.join(work, 'archive'))) {
    const src = JSON.parse(await fs.readFile(path.join(work, 'archive', f), 'utf8'));
    const out = f === 'index.json' ? src : DailyDatasetSchema.parse(toDemo(src));
    await fs.writeFile(path.join(OUT, 'archive', f), `${JSON.stringify(out, null, 2)}\n`);
  }
  const latest = DailyDatasetSchema.parse(toDemo(JSON.parse(await fs.readFile(path.join(work, 'latest.json'), 'utf8'))));
  await fs.writeFile(path.join(OUT, 'latest.json'), `${JSON.stringify(latest, null, 2)}\n`);
  for (const f of ['status.json', 'sources.json']) await fs.copyFile(path.join(work, f), path.join(OUT, f));
  await fs.writeFile(
    path.join(OUT, 'README.md'),
    '# Demonstration data\n\nFictional records generated by `npm run demo:generate` from synthetic test fixtures.\nUsed only by `npm run dev:demo`. Never deployed; `npm run validate:data` rejects `dataset: "demo"` in production data.\n',
  );
  await fs.rm(work, { recursive: true, force: true });
  console.log(`Demo data written to ${OUT} (${latest.records.length} records in latest).`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
